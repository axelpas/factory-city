import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { validateCcJson } from "@factory-city/schema";
import { expect, it } from "vitest";
import { analyze } from "../src/analyze.js";
import { git, makeRepo, makeTree } from "./helpers.js";

const SRC = "export function a(x: number) { if (x) { return 1; } return 2; }\n";

function paths(result: Awaited<ReturnType<typeof analyze>>): string[] {
  const out: string[] = [];
  const walk = (nodes: typeof result.snapshot.files, prefix: string) => {
    for (const n of nodes) {
      const p = prefix ? `${prefix}/${n.name}` : n.name;
      if (n.type === "File") out.push(p.replace(/^root\//, ""));
      else walk(n.children ?? [], p);
    }
  };
  walk(result.snapshot.files, "");
  return out.sort();
}

it("a folder without git > produces a valid cc.json snapshot", async () => {
  const dir = makeTree({ "src/a.ts": SRC, "src/b.js": "const x = 1;\n", "README.md": "# hi\n" });
  const result = await analyze({ folder: dir });
  expect(validateCcJson(result.snapshot)).toEqual({ valid: true, errors: [] });
  expect(paths(result)).toEqual(["src/a.ts", "src/b.js"]);
  expect(result.manifest.git.available).toBe(false);
  expect(result.manifest.source.kind).toBe("disk");
  expect(result.manifest.dataLevel).toBe(0);
});

it("a folder without git > never writes a metric it cannot compute as zero", async () => {
  const dir = makeTree({ "a.ts": "export const a = 1;\n" });
  const result = await analyze({ folder: dir });
  const attrs = Object.values(result.snapshot.lenses.metrics.attributes)[0] ?? {};
  expect(attrs).not.toHaveProperty("max_function_complexity");
  expect(attrs).not.toHaveProperty("recent_commits");
  expect(result.manifest.metrics).not.toContain("max_function_complexity");
});

it("a folder without git > contains no source code, only paths and numbers", async () => {
  const dir = makeTree({ "a.ts": "export const secretToken = 'abc123';\n" });
  const result = await analyze({ folder: dir });
  const text = JSON.stringify(result.snapshot) + JSON.stringify(result.manifest);
  expect(text).not.toContain("secretToken");
  expect(text).not.toContain("abc123");
});

it("a folder without git > is deterministic for the same input", async () => {
  const dir = makeTree({ "b/x.ts": SRC, "a/y.ts": SRC });
  const one = await analyze({ folder: dir });
  const two = await analyze({ folder: dir });
  expect(JSON.stringify(one.snapshot)).toBe(JSON.stringify(two.snapshot));
});

it("a folder without git > handles an empty folder and a folder with no source code", async () => {
  const empty = await analyze({ folder: makeTree({}) });
  expect(empty.manifest.analyzed).toBe(0);
  expect(validateCcJson(empty.snapshot).valid).toBe(true);
  const docs = await analyze({ folder: makeTree({ "notes.md": "x" }) });
  expect(docs.manifest.analyzed).toBe(0);
  expect(docs.manifest.ignored.files.not_source_code).toBe(1);
});

const files: Record<string, string | Buffer> = {
  "src/app.ts": SRC,
  "src/app.test.ts": SRC,
  "node_modules/lib/index.js": "module.exports = 1;\n",
  "dist/out.js": "var a = 1;\n",
  "docs/guide.ts": SRC,
  "public/script.js": "var a = 1;\n",
  "assets/x.ts": SRC,
  "pnpm-lock.yaml": "lock: 1\n",
  "src/vendor.min.js": "var a=1;\n",
  "src/gen.ts": "// Code generated by tool; DO NOT EDIT.\nexport const a = 1;\n",
  "src/image.ts": Buffer.from([0x89, 0x50, 0x00, 0x01]),
  "src/latin1.ts": Buffer.from([0x63, 0x6f, 0x6e, 0x73, 0x74, 0x20, 0xe9, 0x0a]),
  "src/lfs.ts": "version https://git-lfs.github.com/spec/v1\noid sha256:abc\nsize 12\n",
  "ignored.ts": SRC,
  ".gitignore": "ignored.ts\n",
};

it("code-first defaults > keeps engineering code only and says what was left out", async () => {
  const result = await analyze({ folder: makeTree(files) });
  expect(paths(result)).toEqual(["src/app.test.ts", "src/app.ts"]);
  const { ignored } = result.manifest;
  expect(ignored.folders.dependency_or_build_folder).toBe(2);
  expect(ignored.folders.non_engineering_folder).toBe(3);
  expect(ignored.folders.gitignored).toBeUndefined();
  expect(ignored.files["gitignored-file"] ?? ignored.folders["gitignored-file"]).toBe(1);
  expect(ignored.files.generated_or_vendored).toBe(3);
  expect(ignored.warnings).toMatchObject({ binary: 1, non_utf8: 1, lfs_pointer: 1 });
});

/** The metrics of each file of an analysis, by file name. */
function metricsByName(result: Awaited<ReturnType<typeof analyze>>): Map<string, Record<string, number>> {
  const byName = new Map<string, Record<string, number>>();
  const walk = (nodes: typeof result.snapshot.files) => {
    for (const n of nodes) {
      if (n.type === "File") byName.set(n.name, result.snapshot.lenses.metrics.attributes[n.id] ?? {});
      else walk(n.children ?? []);
    }
  };
  walk(result.snapshot.files);
  return byName;
}

it("code-first defaults > flags tests instead of dropping them", async () => {
  const result = await analyze({ folder: makeTree(files) });
  const byName = metricsByName(result);
  expect(byName.get("app.test.ts")?.is_test).toBe(1);
  expect(byName.get("app.ts")?.is_test).toBe(0);
});

it("code-first defaults > --all includes everything that is text", async () => {
  const result = await analyze({ folder: makeTree(files), all: true });
  expect(paths(result)).toContain("docs/guide.ts");
  expect(paths(result)).toContain("pnpm-lock.yaml");
  expect(paths(result)).not.toContain("src/image.ts");
});

it("code-first defaults > --include and --exclude take globs", async () => {
  const included = await analyze({ folder: makeTree(files), include: ["docs/**"] });
  expect(paths(included)).toContain("docs/guide.ts");
  const excluded = await analyze({ folder: makeTree(files), exclude: ["**/*.test.ts"] });
  expect(paths(excluded)).toEqual(["src/app.ts"]);
});

it("code-first defaults > --path restricts the analysis to a subfolder", async () => {
  const result = await analyze({ folder: makeTree({ "a/x.ts": SRC, "b/y.ts": SRC }), path: "a" });
  expect(paths(result)).toEqual(["a/x.ts"]);
});

it("code-first defaults > treats a folder where almost no file is source code as non-engineering", async () => {
  const data: Record<string, string> = { "src/main.ts": SRC, "samples/tool.ts": SRC };
  for (let i = 0; i < 25; i++) data[`samples/row${i}.csv`] = "a,b\n";
  const result = await analyze({ folder: makeTree(data) });
  expect(paths(result)).toEqual(["src/main.ts"]);
  expect(result.manifest.ignored.files.non_engineering_folder).toBe(1);
});

it("a git repository > analyzes HEAD, not uncommitted changes, unless --dirty", async () => {
  const dir = makeRepo({ "a.ts": SRC });
  writeFileSync(join(dir, "b.ts"), SRC);
  const head = await analyze({ folder: dir });
  expect(paths(head)).toEqual(["a.ts"]);
  expect(head.manifest.source.kind).toBe("git");
  expect(head.snapshot.meta.commitHash).toMatch(/^[0-9a-f]{7,}$/);
  const dirty = await analyze({ folder: dir, dirty: true });
  expect(paths(dirty)).toEqual(["a.ts", "b.ts"]);
});

it("a git repository > analyzes a given revision", async () => {
  const dir = makeRepo({ "a.ts": SRC });
  writeFileSync(join(dir, "b.ts"), SRC);
  git(dir, "add", "-A");
  git(dir, "commit", "-q", "-m", "second");
  const first = await analyze({ folder: dir, rev: "HEAD~1" });
  expect(paths(first)).toEqual(["a.ts"]);
  const tip = await analyze({ folder: dir, rev: "HEAD" });
  expect(paths(tip)).toEqual(["a.ts", "b.ts"]);
});

it("a git repository > honors .gitignore through the committed tree", async () => {
  const dir = makeRepo({ "a.ts": SRC, ".gitignore": "ignored.ts\n" });
  writeFileSync(join(dir, "ignored.ts"), SRC);
  const dirty = await analyze({ folder: dir, dirty: true });
  expect(paths(dirty)).toEqual(["a.ts"]);
});

it("a git repository > is read-only: no checkout, no file written", async () => {
  const dir = makeRepo({ "a.ts": SRC, "src/b.ts": SRC });
  const before = readdirSync(dir).sort();
  const mtime = statSync(join(dir, "a.ts")).mtimeMs;
  const status = git(dir, "status", "--porcelain");
  await analyze({ folder: dir });
  await analyze({ folder: dir, rev: "HEAD" });
  expect(readdirSync(dir).sort()).toEqual(before);
  expect(statSync(join(dir, "a.ts")).mtimeMs).toBe(mtime);
  expect(git(dir, "status", "--porcelain")).toBe(status);
});

it("a git repository > analyzes a subfolder of a repository", async () => {
  const dir = makeRepo({ "pkg/a.ts": SRC, "other/b.ts": SRC });
  const result = await analyze({ folder: join(dir, "pkg") });
  expect(paths(result)).toEqual(["a.ts"]);
  expect(result.manifest.source.kind).toBe("git");
});

it("a git repository > falls back to the disk for a repository with no commit", async () => {
  const dir = makeTree({ "a.ts": SRC });
  execFileSync("git", ["init", "-q", "-b", "main"], { cwd: dir });
  const result = await analyze({ folder: dir });
  expect(paths(result)).toEqual(["a.ts"]);
  expect(result.manifest.warnings.join(" ")).toContain("no commit yet");
});

it("a git repository > gives an actionable error for --rev outside a repository", async () => {
  await expect(analyze({ folder: makeTree({ "a.ts": SRC }), rev: "main" })).rejects.toThrow(
    /needs a git repository/,
  );
});

it("a git repository > skips submodules and symlinks with a warning", async () => {
  const dir = makeRepo({ "a.ts": SRC });
  execFileSync("ln", ["-s", "a.ts", join(dir, "link.ts")]);
  git(dir, "add", "-A");
  git(dir, "commit", "-q", "-m", "link");
  const result = await analyze({ folder: dir });
  expect(paths(result)).toEqual(["a.ts"]);
  expect(result.manifest.ignored.warnings.symlink).toBe(1);
});

it("output files > writes a snapshot that validates after a round trip through JSON", async () => {
  const dir = makeTree({ "a.ts": SRC });
  const result = await analyze({ folder: dir });
  const roundTrip = JSON.parse(JSON.stringify(result.snapshot));
  expect(validateCcJson(roundTrip).valid).toBe(true);
  expect(readFileSync).toBeDefined();
});
