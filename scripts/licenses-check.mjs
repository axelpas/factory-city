#!/usr/bin/env node
// Fails on a license outside the policy (brief section 11) and regenerates THIRD-PARTY-NOTICES.md.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const ALLOWED = new Set([
  "MIT",
  "ISC",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "Apache-2.0",
  "0BSD",
  "Unlicense",
  "CC0-1.0",
  "MPL-2.0",
]);

function pnpmLicenses(args) {
  const raw = execFileSync("pnpm", [...args, "licenses", "list", "--json"], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  const byLicense = JSON.parse(raw);
  return Object.values(byLicense).flat();
}

/** SPDX expression: `A OR B` is allowed if one side is; `A AND B` only if both are. */
function isAllowed(expression) {
  const clean = expression.replace(/[()]/g, " ").trim();
  return clean.split(/\s+OR\s+/i).some((alt) => alt.split(/\s+AND\s+/i).every((l) => ALLOWED.has(l.trim())));
}

const all = pnpmLicenses([]);
const prod = pnpmLicenses(["--filter", "./packages/*", "--prod"]);

const violations = all.filter((p) => !isAllowed(p.license ?? "UNKNOWN"));
if (violations.length > 0) {
  console.error("Licenses outside the policy:");
  for (const p of violations) console.error(`  ${p.name}@${p.versions.join(",")}: ${p.license ?? "UNKNOWN"}`);
  process.exit(1);
}

const rows = prod
  .flatMap((p) =>
    p.versions.map((v) => ({ name: p.name, version: v, license: p.license, homepage: p.homepage ?? "" })),
  )
  .sort((a, b) => (a.name + a.version).localeCompare(b.name + b.version));

const notices = [
  "# Third-party notices",
  "",
  "Generated by `pnpm licenses:check`. Do not edit by hand.",
  "",
  "## Dependencies",
  "",
  "| Package | Version | License | Home |",
  "|---|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.homepage} |`),
  "",
  "## Bundled files",
  "",
  "- `packages/schema/src/schemas/cc-json-2.0.schema.json`: the CodeCharta cc.json 2.0 JSON Schema,",
  "  copied unchanged from https://github.com/MaibornWolff/codecharta. Copyright (c) 2024, MaibornWolff GmbH.",
  "  BSD-3-Clause License: redistribution and use in source and binary forms, with or without modification,",
  "  are permitted provided that the copyright notice, the list of conditions and the disclaimer of the",
  "  license are retained, and that the name of the copyright holder is not used to endorse derived products.",
  "",
];
writeFileSync(new URL("../THIRD-PARTY-NOTICES.md", import.meta.url), notices.join("\n"));
console.log(
  `Licenses OK: ${all.length} packages checked, ${rows.length} production packages in THIRD-PARTY-NOTICES.md`,
);
